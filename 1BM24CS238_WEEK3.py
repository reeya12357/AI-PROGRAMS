import heapq

# -------------------------------
# Initial and Goal State
# -------------------------------

initial = (
    2, 8, 3,
    1, 6, 4,
    7, 0, 5
)

goal = (
    1, 2, 3,
    8, 0, 4,
    7, 6, 5
)


# -------------------------------
# Manhattan Distance Heuristic
# -------------------------------

def heuristic(state):
    distance = 0

    for i in range(9):

        tile = state[i]

        # Ignore blank
        if tile == 0:
            continue

        # Current position
        current_row = i // 3
        current_col = i % 3

        # Goal position
        goal_index = goal.index(tile)
        goal_row = goal_index // 3
        goal_col = goal_index % 3

        # Manhattan distance
        distance += abs(current_row - goal_row)
        distance += abs(current_col - goal_col)

    return distance


# -------------------------------
# Generate possible moves
# -------------------------------

def get_neighbors(state):

    neighbors = []

    # Find blank
    blank = state.index(0)

    row = blank // 3
    col = blank % 3

    moves = [
        (-1, 0, "U"),
        (1, 0, "D"),
        (0, -1, "L"),
        (0, 1, "R")
    ]

    for dr, dc, move in moves:

        new_row = row + dr
        new_col = col + dc

        # Check valid position
        if 0 <= new_row < 3 and 0 <= new_col < 3:

            new_blank = new_row * 3 + new_col

            new_state = list(state)

            # Swap blank and tile
            new_state[blank], new_state[new_blank] = \
                new_state[new_blank], new_state[blank]

            neighbors.append(
                (tuple(new_state), move)
            )

    return neighbors


# -------------------------------
# A* Search
# -------------------------------

def a_star():

    # Priority Queue
    # (f, g, state, path)

    pq = []

    h = heuristic(initial)

    heapq.heappush(
        pq,
        (h, 0, initial, [])
    )

    # Store best g value
    visited = {
        initial: 0
    }

    while pq:

        f, g, state, path = heapq.heappop(pq)

        # Goal reached
        if state == goal:
            return path, g

        # Generate children
        for new_state, move in get_neighbors(state):

            new_g = g + 1

            # If this path is better
            if new_state not in visited or new_g < visited[new_state]:

                visited[new_state] = new_g

                h = heuristic(new_state)

                # f(n) = g(n) + h(n)
                new_f = new_g + h

                heapq.heappush(
                    pq,
                    (
                        new_f,
                        new_g,
                        new_state,
                        path + [move]
                    )
                )

    return None, None


