import heapq

# Initial state
initial = (
    2, 8, 3,
    1, 6, 4,
    7, 0, 5
)

# Goal state
goal = (
    1, 2, 3,
    8, 0, 4,
    7, 6, 5
)


# ----------------------------------
# Heuristic: Number of misplaced tiles
# ----------------------------------
def heuristic(state):
    count = 0

    for i in range(9):
        if state[i] != 0 and state[i] != goal[i]:
            count += 1

    return count


# ----------------------------------
# Print the puzzle
# ----------------------------------
def print_state(state):
    for i in range(0, 9, 3):
        print(state[i], state[i+1], state[i+2])
    print()


# ----------------------------------
# Generate neighbouring states
# ----------------------------------
def get_neighbors(state):

    neighbors = []

    # Position of blank
    blank = state.index(0)

    row = blank // 3
    col = blank % 3

    moves = [
        (-1, 0, "U"),  # Up
        (1, 0, "D"),   # Down
        (0, -1, "L"),  # Left
        (0, 1, "R")    # Right
    ]

    for dr, dc, move in moves:

        new_row = row + dr
        new_col = col + dc

        # Check whether move is valid
        if 0 <= new_row < 3 and 0 <= new_col < 3:

            new_blank = new_row * 3 + new_col

            new_state = list(state)

            # Swap blank with adjacent tile
            new_state[blank], new_state[new_blank] = \
                new_state[new_blank], new_state[blank]

            neighbors.append(
                (tuple(new_state), move)
            )

    return neighbors


# ----------------------------------
# A* Algorithm
# ----------------------------------
def a_star():

    # Priority queue
    # (f, g, state, path)
    priority_queue = []

    h = heuristic(initial)

    heapq.heappush(
        priority_queue,
        (h, 0, initial, [])
    )

    # Stores minimum g value found for each state
    visited = {}

    visited[initial] = 0

    while priority_queue:

        f, g, state, path = heapq.heappop(priority_queue)

        # Goal reached
        if state == goal:
            return path, g

        # Generate neighbours
        for new_state, move in get_neighbors(state):

            new_g = g + 1

            # If this is a better path
            if new_state not in visited or new_g < visited[new_state]:

                visited[new_state] = new_g

                h = heuristic(new_state)
                new_f = new_g + h

                heapq.heappush(
                    priority_queue,
                    (
                        new_f,
                        new_g,
                        new_state,
                        path + [move]
                    )
                )

    return None, None


