import random


# Calculate the number of attacking queen pairs
def calculate_cost(board, N):
    cost = 0

    for i in range(N):
        for j in range(i + 1, N):
            if (board[i] == board[j] or
                abs(board[i] - board[j]) == abs(i - j)):
                cost += 1

    return cost


# Display the chessboard
def display_board(board, N):
    print("  " + " ".join(str(i) for i in range(N)))
    for row in range(N):
        print(row, end=" ")
        for col in range(N):
            if board[col] == row:
                print("Q", end=" ")
            else:
                print(".", end=" ")
        print()


# Generate neighbors by swapping pairs of queens
def generate_neighbors(board, N):
    neighbors = []

    for i in range(N):
        for j in range(i + 1, N):
            neighbor = board.copy()
            neighbor[i], neighbor[j] = neighbor[j], neighbor[i]

            cost = calculate_cost(neighbor, N)
            neighbors.append((cost, i, j, neighbor))

    return neighbors


# Hill Climbing algorithm
def hill_climbing():
    N = int(input("Enter the number of queens (N): "))

    if N < 1:
        print("N must be at least 1.")
        return

    if N == 2 or N == 3:
        print("No solution exists for N =", N)
        return

    # Initial configuration from the PPT
    if N == 4:
        board = [3, 1, 2, 0]
    else:
        board = list(range(N))
        random.shuffle(board)

    step = 0

    while True:
        current_cost = calculate_cost(board, N)

        print("\n" + "=" * 35)
        print("STEP:", step)
        print("CURRENT STATE:", board)
        print("CURRENT COST:", current_cost)
        print("CURRENT BOARD:")
        display_board(board, N)

        # Goal test
        if current_cost == 0:
            print("\nGOAL CONFIGURATION REACHED!")
            print("Final solution:", board)
            return

        neighbors = generate_neighbors(board, N)

        print("\nNEIGHBOR STATES AND THEIR BOARDS:")

        for cost, i, j, neighbor in neighbors:
            print(f"\nSwap (x{i}, x{j})")
            print("Neighbor:", neighbor)
            print("Cost:", cost)
            display_board(neighbor, N)

        # Select minimum cost, breaking ties by smallest indices
        best = min(
            neighbors,
            key=lambda item: (item[0], item[1], item[2])
        )

        best_cost, i, j, best_board = best

        # Stop if no improvement is possible
        if best_cost >= current_cost:
            print("\nLOCAL MINIMUM REACHED.")
            print("Restarting with a new initial state...")

            board = list(range(N))
            random.shuffle(board)
            step = 0
            continue

        print("\nSELECTED NEIGHBOR:")
        print("Swapped queens:", (i, j))
        print("Next state:", best_board)
        print("Next cost:", best_cost)

        board = best_board
        step += 1


# Execute the algorithm
hill_climbing()