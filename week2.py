def print_board(state):
    """Utility function to print the 3x3 board cleanly."""
    for i in range(0, 9, 3):
        print(f" {state[i]}  {state[i+1]}  {state[i+2]} ")
    print("-" * 11)

def get_neighbors(state):
    """Generates all valid successor states (Up, Down, Left, Right)."""
    neighbors = []
    zero_idx = state.index(0)
    row, col = zero_idx // 3, zero_idx % 3

    # Offsets for moving the blank tile: Up, Down, Left, Right
    moves = [(-1, 0), (1, 0), (0, -1), (0, 1)]

    for dr, dc in moves:
        new_r, new_c = row + dr, col + dc
        if 0 <= new_r < 3 and 0 <= new_c < 3:
            new_zero_idx = new_r * 3 + new_c
            state_list = list(state)
            # Swap blank space (0) with the target tile
            state_list[zero_idx], state_list[new_zero_idx] = state_list[new_zero_idx], state_list[zero_idx]
            neighbors.append(tuple(state_list))

    return neighbors

def depth_limited_search(state, goal_state, limit, path, visited):
    """Inner Depth-Limited Search (DLS) recursive function."""
    # 1. Goal Check
    if state == goal_state:
        return path

    # 2. Limit Check
    if limit <= 0:
        return None

    # 3. Successor Expansion & Backtracking
    for neighbor in get_neighbors(state):
        if neighbor not in visited:
            visited.add(neighbor)
            result = depth_limited_search(neighbor, goal_state, limit - 1, path + [neighbor], visited)
            if result is not None:
                return result
            visited.remove(neighbor)  # Backtrack step

    return None

def iterative_deepening_search(start_state, goal_state, max_depth=20):
    """Outer IDS loop that increments depth limit iteratively."""
    for depth in range(max_depth + 1):
        print(f"Searching at Depth Limit = {depth}...")
        visited = {start_state}
        result = depth_limited_search(start_state, goal_state, depth, [start_state], visited)

        if result is not None:
            return result, depth

    return None, max_depth

